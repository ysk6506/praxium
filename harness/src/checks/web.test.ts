import { createHash } from "node:crypto";
import { describe, expect, test } from "vitest";
import { miniRepo } from "../test-support/mini-repo";
import {
  backendViolations,
  colorViolations,
  dependencyViolations,
  generatedViolations,
  loadWebConfig,
} from "./web";

const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const CONFIG = `
package: apps/web/package.json
dependencies: [react]
dev_dependencies: [vite]
token_file: apps/web/src/ui/tokens.css
scan: [apps/web/src]
contract: contract.json
generated_dir: apps/web/src/api/generated
generator_script: scripts/web-gen-api.ts
backend:
  root: backend
  embed_dir: backend/internal/webui/dist
  placeholder: backend/internal/webui/dist/placeholder.html
  forbidden_reference: apps/web
  gitignore: .gitignore
  ignore_lines: ["backend/internal/webui/dist/*"]
`;

const repo = (files: Record<string, string>) =>
  miniRepo({ "harness/config/web.yaml": CONFIG, ...files }, {});
const codes = (list: { code: string }[]) => list.map((v) => v.code);

function generated(contract: string, body: string, bodyHash = sha(body)): string {
  return [
    "// Generated by the generator. Do not edit by hand.",
    "// Regenerate with `pnpm web:gen-api`.",
    `// contract-sha256: ${sha(contract)}`,
    `// body-sha256: ${bodyHash}`,
    "",
    body,
  ].join("\n");
}

describe("the dependencies of apps/web are on an allow-list [REQ-277]", () => {
  test("listed dependencies pass, others are WEB001 in every kind", () => {
    const root = repo({
      "apps/web/package.json": JSON.stringify({
        dependencies: { react: "1", lodash: "1" },
        devDependencies: { vite: "1", jest: "1" },
        peerDependencies: { moment: "1" },
      }),
    });
    const found = dependencyViolations(root, loadWebConfig(root));
    expect(codes(found)).toEqual(["WEB001", "WEB001", "WEB001"]);
    expect(found.map((v) => v.message).join(" ")).toMatch(/lodash.*jest.*|moment/s);
  });

  test("a package that lists only allowed names is clean", () => {
    const root = repo({
      "apps/web/package.json": JSON.stringify({
        dependencies: { react: "1" },
        devDependencies: { vite: "1" },
      }),
    });
    expect(dependencyViolations(root, loadWebConfig(root))).toEqual([]);
  });
});

describe("the generated API layer matches the contract [REQ-276]", () => {
  const contract = '{"openapi":"3.1.0"}';
  const dir = "apps/web/src/api/generated";
  const check = (files: Record<string, string>) => {
    const root = repo({ "contract.json": contract, "apps/web/package.json": "{}", ...files });
    return codes(generatedViolations(root, loadWebConfig(root)));
  };

  test("a file made from this contract with its own body passes", () => {
    expect(check({ [`${dir}/a.ts`]: generated(contract, "export const a = 1;\n") })).toEqual([]);
  });

  test("a file made from another contract is WEB010", () => {
    expect(check({ [`${dir}/a.ts`]: generated('{"other":1}', "export const a = 1;\n") })).toEqual([
      "WEB010",
    ]);
  });

  test("a hand-edited body is WEB011", () => {
    const text = generated(contract, "export const a = 1;\n").replace("a = 1", "a = 2");
    expect(check({ [`${dir}/a.ts`]: text })).toEqual(["WEB011"]);
  });

  test("a file without the header and a missing folder are WEB012", () => {
    expect(check({ [`${dir}/a.ts`]: "export const a = 1;\n" })).toEqual(["WEB012"]);
    expect(check({})).toEqual(["WEB012"]);
  });
});

describe("colors are written in the token file only [REQ-277]", () => {
  const scan = (files: Record<string, string>) => {
    const root = repo(files);
    return colorViolations(root, loadWebConfig(root)).map((v) => `${v.code}:${v.path}:${v.line}`);
  };

  test("literals outside the token file are WEB020, inside it they are fine", () => {
    expect(
      scan({
        "apps/web/src/ui/tokens.css": ":root { --px-a: oklch(0.5 0.1 20); --px-b: #fff; }\n",
        "apps/web/src/screens/A.tsx": 'const a = "#1a2b3c";\nconst b = "rgb(0 0 0)";\n',
        "apps/web/src/app.css": "a { color: hsl(10 10% 10%); }\n",
      }),
    ).toEqual([
      "WEB020:apps/web/src/app.css:1",
      "WEB020:apps/web/src/screens/A.tsx:1",
      "WEB020:apps/web/src/screens/A.tsx:2",
    ]);
  });

  test("arbitrary Tailwind colors, palette names, white and black are WEB021", () => {
    expect(
      scan({
        "apps/web/src/screens/A.tsx": [
          '<p className="bg-[color:var(--x)]" />',
          '<p className="text-red-500" />',
          '<p className="border-white" />',
          '<p className="bg-[#fff]" />',
        ].join("\n"),
      }),
    ).toEqual([
      "WEB021:apps/web/src/screens/A.tsx:1",
      "WEB021:apps/web/src/screens/A.tsx:2",
      "WEB021:apps/web/src/screens/A.tsx:3",
      "WEB020:apps/web/src/screens/A.tsx:4",
    ]);
  });

  test("token names, hash routes and sizes are not colors", () => {
    expect(
      scan({
        "apps/web/src/screens/A.tsx":
          'const r = "#/kg/main"; const c = "bg-surface text-muted border-line w-[12rem] text-accent";\n',
      }),
    ).toEqual([]);
  });
});

describe("the backend builds without apps/web [REQ-279]", () => {
  const scan = (files: Record<string, string>) => {
    const root = repo(files);
    return codes(backendViolations(root, loadWebConfig(root)));
  };
  const healthy = {
    "backend/internal/webui/dist/placeholder.html": "<p>none</p>",
    ".gitignore": "backend/internal/webui/dist/*\n",
    "backend/main.go": "package main\n",
  };

  test("a placeholder, the ignore line and clean Go code pass", () => {
    expect(scan(healthy)).toEqual([]);
  });

  test("a missing placeholder is WEB030, a Go reference WEB031, a missing ignore line WEB032", () => {
    expect(
      scan({ ...healthy, "backend/main.go": "// ../../apps/web/dist\npackage main\n" }),
    ).toEqual(["WEB031"]);
    expect(scan({ ...healthy, ".gitignore": "node_modules\n" })).toEqual(["WEB032"]);
    expect(
      scan({ "backend/main.go": "package main\n", ".gitignore": "backend/internal/webui/dist/*" }),
    ).toEqual(["WEB030"]);
  });
});
